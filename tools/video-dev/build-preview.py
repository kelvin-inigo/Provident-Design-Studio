"""Builds the Video Studio's placement preview from CAS's.

CAS draws the phone frames and the Facebook / Instagram chrome in its own template and
stylesheet. This reads both out of `Provident Campaign Studio.dc.html` and writes:

    video-preview.css   the .mk-* rules, verbatim
    video-preview.js    window.providentVideoPreview = { 'fb:feed': html, 'fb:reel': ..., ... }

with the creative's <img> swapped for a <canvas class="mk-shot"> the editor mirrors into.
Run it again when CAS's preview changes:   python3 tools/video-dev/build-preview.py
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
src = open(os.path.join(ROOT, 'Provident Campaign Studio.dc.html'), encoding='utf-8').read()
lines = src.split('\n')

# ── the stylesheet: the contiguous preview block, then every later rule that starts .mk- ──
start = next(i for i, l in enumerate(lines) if l.startswith('.mk-ov{'))
end = next(i for i in range(start, len(lines)) if lines[i].startswith('.mk-story .mk-homebar'))
css = lines[start:end + 1]
i = end + 1
style_end = next(k for k in range(end, len(lines)) if '</style>' in lines[k] or '</helmet>' in lines[k])
while i < style_end:
    l = lines[i]
    if l.startswith('.mk-') or (l.startswith('@media') and '.mk-' in l):
        depth = 0
        while i < style_end:
            css.append(lines[i])
            depth += lines[i].count('{') - lines[i].count('}')
            i += 1
            if depth <= 0 and '{' in ''.join(css[-6:]):
                break
        continue
    i += 1
css_text = '/* GENERATED by tools/video-dev/build-preview.py from CAS. Do not edit. */\n' + '\n'.join(css) + '\n'
css_text = css_text.replace('animation:pSelIn .18s ease-out both', '')
open(os.path.join(ROOT, 'video-preview.css'), 'w', encoding='utf-8').write(css_text)

# ── the template: one phone, evaluated for each app and placement ──
a = src.index('<div class="mk-phone">', src.index('<div class="mk-ov">'))
b = src.index('</figure></sc-for>', a)
tpl = src[a:b]

TOK = re.compile(r'<sc-if value="\{\{\s*([^}]+?)\s*\}\}"[^>]*>|</sc-if>')


def render(t, ctx):
    out, stack, pos = [], [True], 0
    for m in TOK.finditer(t):
        if all(stack):
            out.append(t[pos:m.start()])
        pos = m.end()
        if m.group(0).startswith('</'):
            stack.pop()
        else:
            stack.append(bool(ctx.get(m.group(1))))
    out.append(t[pos:])
    h = ''.join(out)

    def attr(m):                                   # an undefined value drops the attribute
        v = ctx.get(m.group(2))
        return '' if v is None else ' %s="%s"' % (m.group(1), v)
    h = re.sub(r'\s([a-z-]+)="\{\{\s*([^}]+?)\s*\}\}"', attr, h)
    h = re.sub(r'<img class="mk-shot"[^>]*>', '<canvas class="mk-shot"></canvas>', h)
    # what is left is copy: keep it as a marker the editor fills in
    h = re.sub(r'\{\{\s*mkCopy\.([a-z]+)\s*\}\}', r'[[\1]]', h)
    h = re.sub(r'\{\{\s*mkStoryName\s*\}\}', '[[story]]', h)
    assert '{{' not in h and 'sc-if' not in h, re.findall(r'\{\{[^}]*\}\}', h)[:5]
    return re.sub(r'>\s+<', '><', h).strip()


out = {}
for plat in ('fb', 'ig'):
    for view in ('feed', 'reel', 'story'):
        fb = plat == 'fb'
        ctx = {
            'true': True, 'false': False, 'mkChromeOn': True, 'mkIsFb': fb, 'mkIsIg': not fb,
            'mkPlatKey': plat, 'mkModeKey': '[[mode]]', 'mkUnb': None,
            'ph.view': view, 'ph.isFeed': view == 'feed', 'ph.isReel': view == 'reel', 'ph.isStory': view == 'story',
            'ph.has': True, 'ph.none': False, 'ph.src': '',
            'ph.full': '1' if view == 'reel' else None,
            'ph.fbr': '1' if (view == 'reel' and fb) else None,
            'ph.igr': '1' if (view == 'reel' and not fb) else None,
        }
        out[plat + ':' + view] = render(tpl, ctx)
open(os.path.join(ROOT, 'video-preview.js'), 'w', encoding='utf-8').write(
    '/* GENERATED by tools/video-dev/build-preview.py from CAS. Do not edit. */\nwindow.providentVideoPreview = ' + json.dumps(out) + ';\n')
print('css', len(css_text), 'bytes;', {k: len(v) for k, v in out.items()})
